#!/usr/bin/env python3
"""Generate static repository maps, or check their exact content without writes.

This tool reads files and Git metadata only. It never imports runtime modules,
contacts services, builds embeddings or touches a pyramid store.
"""
import argparse
import ast
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = ("docs/codebase-overview.md", "docs/high_signal_file_index.json",
           "llms.txt", "llms-small.txt", "llms-full.txt", "llms-facts.txt")
DOCS = ("README.md", "CLAUDE.md", "docs/ARCHITECTURE.md", "docs/COMPONENTS.md",
        "docs/DEVELOPMENT.md", "docs/TESTING.md", "docs/known-issues.md")
GENERATED_SUMMARIES = dict(zip(OUTPUTS, (
    "Generated complete repository file map",
    "Generated machine-readable source and validation index",
    "Generated repository documentation index",
    "Generated concise repository digest",
    "Generated bundle of current repository documentation",
    "Generated source-tagged project facts",
)))


def census():
    result = subprocess.run(["git", "ls-files", "--cached", "--others",
                             "--exclude-standard", "-z"], cwd=ROOT,
                            capture_output=True, check=True)
    return sorted({p.decode("utf-8") for p in result.stdout.split(b"\0")
                   if p and (ROOT / p.decode("utf-8")).is_file()})


def describe(path):
    # Do not derive generated-file descriptions from their previous output:
    # doing so makes the first refresh depend on stale headers and need two runs.
    if path in GENERATED_SUMMARIES:
        return GENERATED_SUMMARIES[path]
    text = (ROOT / path).read_text(encoding="utf-8")
    if path.endswith(".py"):
        module = ast.parse(text)
        doc = ast.get_docstring(module)
        if doc:
            return " ".join(doc.splitlines()[0].split())
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    if path.startswith(".github/workflows/"):
        return "GitHub Actions validation workflow"
    if path.endswith(".json"):
        return "JSON configuration, schema, index or example data"
    if path.startswith("deploy/"):
        return "Optional systemd deployment configuration"
    return "Repository configuration or supporting file"


def render():
    paths = census()
    summaries = {path: describe(path) for path in paths}
    overview = ["# Codebase overview", "", "Generated by `python3 scripts/repo_docs.py`; do not edit.",
                "Every tracked or non-ignored file appears below. Local runtime and virtual-environment files are excluded.", "",
                "| Path | Purpose |", "|---|---|"]
    overview.extend(f"| `{path}` | {summaries[path].replace('|', '/')} |" for path in paths)
    significant = [p for p in paths if p.endswith((".py", ".sh")) or p in
                   {"pyproject.toml", "memory_pyramid_schema.json", ".github/workflows/ci.yml"}]
    index = {"$comment": "Generated by scripts/repo_docs.py; static retrieval map, no embeddings.",
             "files": [{"path": path, "signal": "high", "summary": summaries[path]}
                       for path in significant]}
    index_lines = ["# NapMem repository index", "", "> Python memory pyramid: source logs → records → tracks → profiles.", "",
                   "## Documentation"]
    index_lines.extend(f"- [{path}]({path}): {summaries[path]}" for path in DOCS)
    index_lines += ["", "## Source and validation"]
    index_lines.extend(f"- [{path}]({path}): {summaries[path]}" for path in significant)
    index_lines += ["", "## Context files", "- [Digest](llms-small.txt)",
                    "- [Full docs](llms-full.txt)", "- [Sourced facts](llms-facts.txt)"]
    facts = [
        "The package requires Python 3.11+ and ollama-client; Anthropic is optional. [src: pyproject.toml]",
        "The pyramid has four layers: raw sessions, atomic records, tracks and profiles. [src: README.md]",
        "Stable record IDs survive re-ingestion and duplicate anchors remain resolvable. [src: CLAUDE.md]",
        "Layers 2–3 derive from Layer 1; store writes use atomic replacement. [src: CLAUDE.md]",
        "Auto extraction tries Anthropic, then Ollama, then heuristics; ollama mode makes no Anthropic calls. [src: CLAUDE.md]",
        "The consolidator persists mtime and sha256 state beside the pyramid. [src: CLAUDE.md]",
        "MCP exposes search_memory, inspect_provenance, get_topic_track and memory_stats. [src: napmem_mcp_server.py#TOOLS]",
        "The failover proxy starts a local mirrored server when remote SSH fails. [src: napmem_mcp_failover.py]",
        "Semantic retrieval can write a disposable embedding cache. [src: semantic_index.py#SemanticIndex]",
        "Only one writer may update a pyramid store at a time. [src: docs/known-issues.md]",
        "The checked-in example store is separate from production. [src: CLAUDE.md]",
        "Tests use unittest, temporary stores and mocked remote transports. [src: docs/TESTING.md]",
    ]
    small = ["# NapMem digest", "", *["- " + x for x in facts[:8]], "",
             'Validate: `python3 -m unittest discover -s . -p "test_*.py"` after activating the project venv. [src: docs/INSTALLATION.md]',
             "See llms.txt for current source and documentation paths."]
    full = ["# NapMem documentation bundle", "", "Generated by `python3 scripts/repo_docs.py`; source sections follow."]
    for doc in DOCS:
        full += ["", f"## Source: {doc}", "", (ROOT / doc).read_text().rstrip()]
    return dict(zip(OUTPUTS, ("\n".join(overview) + "\n", json.dumps(index, indent=2) + "\n",
                             "\n".join(index_lines) + "\n", "\n".join(small) + "\n",
                             "\n".join(full) + "\n", "# NapMem sourced facts\n\n" + "\n".join("- " + x for x in facts) + "\n")))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on missing or stale generated maps; write nothing.")
    args = parser.parse_args()
    stale = []
    for path, expected in render().items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != expected:
                stale.append(path)
        else:
            target.write_text(expected)
    if stale:
        print("Stale repository docs: " + ", ".join(stale), file=sys.stderr)
        print("Run: python3 scripts/repo_docs.py", file=sys.stderr)
        return 1
    print(f"Repository maps {'checked' if args.check else 'generated'}: {len(OUTPUTS)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
